#!/usr/bin/env bash
# validate.sh - safe, offline-friendly validation for the aws-zero-trust-reference-architecture repo.
#
# It does NOT call AWS, does NOT run `terraform plan` against a real backend, and does NOT
# run `terraform apply`. It checks:
#   - forbidden / sensitive filenames are absent
#   - terraform formatting (fmt -check)
#   - terraform init + validate for each example
#   - terraform test for modules that ship native tests
#   - python static security-invariant tests (pytest)
#   - checkov IaC scanning (if installed)
#   - basic YAML/JSON well-formedness (if python is available)
#
# Usage:  bash scripts/validate.sh [--report docs/validation-report.md]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# Enable offline validation: source fake placeholder AWS env vars (not real/valid/live/
# sandbox/test-account credentials) and tell the examples to skip AWS credential,
# metadata, and account-id checks. No AWS API calls are made; terraform plan/apply are
# never run by this script. See scripts/offline-env.sh.
# shellcheck source=/dev/null
source "$ROOT/scripts/offline-env.sh"
export TF_VAR_offline_validation=true

REPORT=""
if [[ "${1:-}" == "--report" ]]; then
  REPORT="${2:-docs/validation-report.md}"
  : > "$REPORT"
fi

log() { echo "[validate] $*"; }
fail() { echo "[validate][FAIL] $*" >&2; FAILED=1; }
record() { if [[ -n "$REPORT" ]]; then echo "$*" >> "$REPORT"; fi; }

FAILED=0
STEPS=0
PASSED=0

begin() { STEPS=$((STEPS+1)); }
ok()    { PASSED=$((PASSED+1)); echo "[validate][PASS] $*"; record "- PASS: $*"; }
skip()  { echo "[validate][SKIP] $*"; record "- SKIP: $*"; }

record "# Validation report"
record ""
record "Generated by scripts/validate.sh. No AWS credentials were used; no terraform plan/apply was run."
record ""

# -----------------------------------------------------------------------------
# 1) Forbidden / sensitive filenames
# -----------------------------------------------------------------------------
begin
log "checking for forbidden/sensitive files"
FORBIDDEN_RE='\.(tfstate|tfstate\.backup|pem|key|p12|pfx)$|(^|/)(terraform\.tfvars|\.env|secrets\.tfvars|.*\.auto\.tfvars)$|(^|/)\.terraform/|(^|/)terraform\.tfstate$'
HITS=""
if command -v git >/dev/null 2>&1 && git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  # Only inspect tracked files (ignores .gitignore'd local artifacts).
  mapfile -t TRACKED < <(git ls-files)
  for f in "${TRACKED[@]}"; do
    if [[ "$f" =~ $FORBIDDEN_RE ]]; then HITS="$HITS\n  $f"; fi
  done
fi
if [[ -n "$HITS" ]]; then
  fail "forbidden/sensitive tracked files found:$HITS"
  record "- FAIL: forbidden/sensitive tracked files found:$HITS"
else
  ok "no forbidden/sensitive tracked files"
fi

# -----------------------------------------------------------------------------
# 2) terraform fmt -check -recursive
# -----------------------------------------------------------------------------
begin
log "terraform fmt -check -recursive"
if command -v terraform >/dev/null 2>&1; then
  if terraform fmt -check -recursive -write=false "$ROOT" >/tmp/fmt.out 2>&1; then
    ok "terraform fmt -check -recursive"
  else
    fail "terraform fmt found issues:"
    sed 's/^/    /' /tmp/fmt.out >&2
    record "- FAIL: terraform fmt found issues (see /tmp/fmt.out)"
  fi
else
  skip "terraform not installed (fmt -check)"
fi

# -----------------------------------------------------------------------------
# 3) terraform init + validate for each example
# -----------------------------------------------------------------------------
for ex in examples/production examples/lab; do
  begin
  log "terraform validate: $ex"
  if command -v terraform >/dev/null 2>&1; then
    if (cd "$ex" && terraform init -backend=false -input=false -lock=false >/dev/null 2>&1 && terraform validate >/tmp/val.out 2>&1); then
      ok "terraform validate: $ex"
    else
      fail "terraform validate failed for $ex"
      sed 's/^/    /' /tmp/val.out >&2
      record "- FAIL: terraform validate failed for $ex"
    fi
  else
    skip "terraform not installed (validate $ex)"
  fi
done

# -----------------------------------------------------------------------------
# 4) terraform test for modules with native tests
# -----------------------------------------------------------------------------
for mod in modules/rds modules/network; do
  if [[ -d "$mod/tests" ]]; then
    begin
    log "terraform test: $mod"
    if command -v terraform >/dev/null 2>&1; then
      if (cd "$mod" && terraform init -backend=false -input=false -lock=false >/dev/null 2>&1 && terraform test >/tmp/tftest.out 2>&1); then
        ok "terraform test: $mod"
      else
        fail "terraform test failed for $mod"
        sed 's/^/    /' /tmp/tftest.out >&2
        record "- FAIL: terraform test failed for $mod"
      fi
    else
      skip "terraform not installed (test $mod)"
    fi
  fi
done

# -----------------------------------------------------------------------------
# 5) python static security-invariant tests
# -----------------------------------------------------------------------------
begin
log "python security-invariant tests (pytest)"
if command -v python3 >/dev/null 2>&1 || command -v python >/dev/null 2>&1; then
  PY=python3; command -v python3 >/dev/null 2>&1 || PY=python
  if $PY -m pytest tests/python -q >/tmp/pytest.out 2>&1; then
    ok "python security-invariant tests"
  else
    fail "python security-invariant tests failed"
    sed 's/^/    /' /tmp/pytest.out >&2
    record "- FAIL: python security-invariant tests"
  fi
else
  skip "python not installed (pytest)"
fi

# -----------------------------------------------------------------------------
# 6) checkov IaC scan (optional)
# -----------------------------------------------------------------------------
begin
log "checkov IaC scan"
if command -v checkov >/dev/null 2>&1; then
  if checkov -d examples/production --framework terraform --quiet --soft-fail >/tmp/checkov.out 2>&1; then
    ok "checkov scan (examples/production)"
  else
    fail "checkov scan reported failures"
    sed 's/^/    /' /tmp/checkov.out >&2
    record "- FAIL: checkov scan reported failures"
  fi
else
  skip "checkov not installed (IaC scan)"
fi

# -----------------------------------------------------------------------------
# 7) YAML/JSON well-formedness (optional, via python)
# -----------------------------------------------------------------------------
begin
log "YAML/JSON well-formedness"
if command -v python3 >/dev/null 2>&1 || command -v python >/dev/null 2>&1; then
  PY=python3; command -v python3 >/dev/null 2>&1 || PY=python
  if $PY scripts/_check_yaml_json.py >/tmp/yj.out 2>&1; then
    ok "YAML/JSON well-formedness"
  else
    fail "YAML/JSON well-formedness"
    sed 's/^/    /' /tmp/yj.out >&2
    record "- FAIL: YAML/JSON well-formedness"
  fi
else
  skip "python not installed (YAML/JSON check)"
fi

record ""
record "Summary: $PASSED passed, $((STEPS-PASSED)) failed/skipped-out-of $STEPS steps"
echo ""
echo "[validate] Summary: $PASSED passed, $((STEPS-PASSED)) failed/skipped out of $STEPS steps"
exit $FAILED
